"""rocket.lock: read, validate and write the resolved-artifact lock file.

The lock file lives next to server.toml. It records the resolved Paper build and every
resolved plugin artifact (declared identity, download URL, upstream size/checksum), so a
later run can reuse the same artifacts without querying the providers again. The file is
rewritten only when resolution produces a different result.
"""

from __future__ import annotations

import os
import re
import tempfile
import tomllib
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from .errors import LockError
from .models import ArtifactKind, Checksum

LOCK_FILENAME = "rocket.lock"
LOCK_VERSION = 1
_RESOLVER_CHOICES = ("auto", "direct", "github_release")
_SHA256_RE = re.compile(r"[0-9a-fA-F]{64}")
_SHA512_RE = re.compile(r"[0-9a-fA-F]{128}")
_BARE_KEY_RE = re.compile(r"[A-Za-z0-9_-]+")


@dataclass(frozen=True)
class LockedEntry:
    """One resolved artifact recorded in rocket.lock.

    ``provider``/``project``/``version`` plus the paper/plugin identity fields describe the
    declared item the entry belongs to; ``url`` and the remaining fields describe the
    resolved artifact, mirroring :class:`rocket.models.Artifact` without the local target.
    """

    kind: ArtifactKind
    provider: str
    project: str
    version: str
    url: str
    upstream_filename: str | None = None
    size: int | None = None
    checksum: Checksum | None = None
    detail: str | None = None
    source_chain: tuple[str, ...] = ()
    build: int | None = None
    channel: str = "STABLE"
    asset: str | None = None
    resolver: str = "auto"
    follow_external: bool = True


@dataclass(frozen=True)
class LockData:
    """Parsed rocket.lock: the resolved Paper build plus resolved plugin artifacts."""

    paper: LockedEntry | None = None
    plugins: dict[str, LockedEntry] = field(default_factory=dict)


def load_lock(path: Path) -> tuple[LockData | None, tuple[str, ...]]:
    """Read and validate a lock file.

    Returns ``(None, ())`` when the file does not exist, ``(None, warnings)`` when the whole
    file is unusable, and a (possibly partial) LockData with warnings when only individual
    entries are invalid; entries that fail validation are left out and re-resolved by the
    next run.
    """
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None, ()
    except OSError as exc:
        return None, (f"cannot read {path}: {exc}; the lock will be regenerated",)
    try:
        raw = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return None, (f"{path} is not valid TOML ({exc}); the lock will be regenerated",)
    version = raw.get("version")
    if version != LOCK_VERSION:
        return None, (
            f"{path} has unsupported lock version {version!r} (expected {LOCK_VERSION}); "
            "the lock will be regenerated",
        )

    warnings: list[str] = []
    paper = _parse_paper(raw["paper"], warnings) if "paper" in raw else None
    plugins: dict[str, LockedEntry] = {}
    plugins_raw = raw.get("plugins")
    if plugins_raw is None:
        pass
    elif isinstance(plugins_raw, dict):
        for plugin_id, item in plugins_raw.items():
            entry = _parse_plugin(plugin_id, item, warnings)
            if entry is not None:
                plugins[plugin_id] = entry
    else:
        warnings.append(f"{path}: [plugins] is not a table; plugin entries are ignored")
    return LockData(paper=paper, plugins=plugins), tuple(warnings)


def write_lock(path: Path, lock: LockData) -> bool:
    """Write the lock file atomically; return whether its content changed."""
    text = serialize_lock(lock)
    try:
        if path.read_text(encoding="utf-8") == text:
            return False
    except OSError:
        pass
    temp_path: Path | None = None
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        descriptor, temp_name = tempfile.mkstemp(
            prefix=f".{path.name}.", suffix=".tmp", dir=path.parent
        )
        os.close(descriptor)
        temp_path = Path(temp_name)
        temp_path.write_text(text, encoding="utf-8")
        os.replace(temp_path, path)
    except OSError as exc:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)
        raise LockError(
            f"cannot write lock file {path}: {exc}",
            hint="check the config directory write permissions and free space",
        ) from exc
    return True


def serialize_lock(lock: LockData) -> str:
    """Render the lock file deterministically (plugin ids are sorted)."""
    lines = [
        "# rocket.lock is generated by rocket and pins the resolved Paper build and plugin",
        "# artifacts declared in server.toml; manual edits are overwritten.",
        "# Run `rocket download --upgrade` to re-resolve everything and rewrite this file.",
        "",
        f"version = {LOCK_VERSION}",
    ]
    if lock.paper is not None:
        lines.append("")
        lines.extend(_serialize_paper(lock.paper))
    for plugin_id in sorted(lock.plugins):
        lines.append("")
        lines.extend(_serialize_plugin(plugin_id, lock.plugins[plugin_id]))
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Parsing
# ---------------------------------------------------------------------------


class _InvalidEntry(Exception):
    """Raised while parsing one invalid lock entry."""


def _parse_paper(value: Any, warnings: list[str]) -> LockedEntry | None:
    if not isinstance(value, dict):
        warnings.append("[paper] lock entry is not a table; it will be resolved again")
        return None
    try:
        return LockedEntry(
            kind=ArtifactKind.PAPER,
            provider=_required_str(value, "provider"),
            project=_required_str(value, "project"),
            version=_required_str(value, "version"),
            url=_required_str(value, "url"),
            build=_required_build(value),
            channel=_optional_str(value, "channel") or "STABLE",
            upstream_filename=_optional_str(value, "upstream_filename"),
            size=_optional_size(value),
            checksum=_parse_checksum(value),
            detail=_optional_str(value, "detail"),
            source_chain=_parse_source_chain(value),
        )
    except _InvalidEntry as exc:
        warnings.append(f"[paper] lock entry is invalid ({exc}); it will be resolved again")
        return None


def _parse_plugin(plugin_id: str, value: Any, warnings: list[str]) -> LockedEntry | None:
    if not isinstance(value, dict):
        warnings.append(
            f"[plugins.{plugin_id}] lock entry is not a table; it will be resolved again"
        )
        return None
    try:
        resolver = value.get("resolver", "auto")
        if resolver not in _RESOLVER_CHOICES:
            raise _InvalidEntry(f"resolver must be one of {', '.join(_RESOLVER_CHOICES)}")
        follow_external = value.get("follow_external", True)
        if not isinstance(follow_external, bool):
            raise _InvalidEntry("follow_external must be a boolean")
        return LockedEntry(
            kind=ArtifactKind.PLUGIN,
            provider=_required_str(value, "provider"),
            project=_required_str(value, "project"),
            version=_required_str(value, "version"),
            url=_required_str(value, "url"),
            upstream_filename=_optional_str(value, "upstream_filename"),
            size=_optional_size(value),
            checksum=_parse_checksum(value),
            detail=_optional_str(value, "detail"),
            source_chain=_parse_source_chain(value),
            asset=_optional_str(value, "asset"),
            resolver=resolver,
            follow_external=follow_external,
        )
    except _InvalidEntry as exc:
        warnings.append(
            f"[plugins.{plugin_id}] lock entry is invalid ({exc}); it will be resolved again"
        )
        return None


def _required_str(table: dict[str, Any], key: str) -> str:
    value = table.get(key)
    if not isinstance(value, str) or not value:
        raise _InvalidEntry(f"{key} must be a non-empty string")
    return value


def _optional_str(table: dict[str, Any], key: str) -> str | None:
    value = table.get(key)
    if value is None:
        return None
    if not isinstance(value, str) or not value:
        raise _InvalidEntry(f"{key} must be a non-empty string when present")
    return value


def _required_build(table: dict[str, Any]) -> int:
    value = table.get("build")
    if isinstance(value, bool) or not isinstance(value, int) or value < 1:
        raise _InvalidEntry("build must be a positive integer")
    return value


def _optional_size(table: dict[str, Any]) -> int | None:
    value = table.get("size")
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise _InvalidEntry("size must be a non-negative integer when present")
    return value


def _parse_checksum(table: dict[str, Any]) -> Checksum | None:
    sha256 = table.get("sha256")
    if sha256 is not None:
        if not isinstance(sha256, str) or not _SHA256_RE.fullmatch(sha256):
            raise _InvalidEntry("sha256 must be 64 hex characters")
        return Checksum(algorithm="sha256", value=sha256.lower())
    sha512 = table.get("sha512")
    if sha512 is not None:
        if not isinstance(sha512, str) or not _SHA512_RE.fullmatch(sha512):
            raise _InvalidEntry("sha512 must be 128 hex characters")
        return Checksum(algorithm="sha512", value=sha512.lower())
    return None


def _parse_source_chain(table: dict[str, Any]) -> tuple[str, ...]:
    value = table.get("source_chain")
    if value is None:
        return ()
    if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
        raise _InvalidEntry("source_chain must be an array of strings")
    return tuple(value)


# ---------------------------------------------------------------------------
# Serialization
# ---------------------------------------------------------------------------


def _serialize_paper(entry: LockedEntry) -> list[str]:
    lines = [
        "[paper]",
        f"version = {_toml_string(entry.version)}",
        f"channel = {_toml_string(entry.channel)}",
    ]
    if entry.build is not None:
        lines.append(f"build = {entry.build}")
    lines.extend(_artifact_lines(entry, include_provider=True))
    return lines


def _serialize_plugin(plugin_id: str, entry: LockedEntry) -> list[str]:
    lines = [
        f"[plugins.{_toml_key(plugin_id)}]",
        f"provider = {_toml_string(entry.provider)}",
        f"project = {_toml_string(entry.project)}",
        f"version = {_toml_string(entry.version)}",
    ]
    if entry.asset is not None:
        lines.append(f"asset = {_toml_string(entry.asset)}")
    lines.append(f"resolver = {_toml_string(entry.resolver)}")
    lines.append(f"follow_external = {'true' if entry.follow_external else 'false'}")
    lines.extend(_artifact_lines(entry, include_provider=False))
    return lines


def _artifact_lines(entry: LockedEntry, *, include_provider: bool) -> list[str]:
    lines: list[str] = []
    if include_provider:
        lines.append(f"provider = {_toml_string(entry.provider)}")
        lines.append(f"project = {_toml_string(entry.project)}")
    lines.append(f"url = {_toml_string(entry.url)}")
    if entry.upstream_filename is not None:
        lines.append(f"upstream_filename = {_toml_string(entry.upstream_filename)}")
    if entry.size is not None:
        lines.append(f"size = {entry.size}")
    if entry.checksum is not None:
        lines.append(f"{entry.checksum.algorithm} = {_toml_string(entry.checksum.value)}")
    if entry.detail is not None:
        lines.append(f"detail = {_toml_string(entry.detail)}")
    if entry.source_chain:
        chain = ", ".join(_toml_string(item) for item in entry.source_chain)
        lines.append(f"source_chain = [{chain}]")
    return lines


def _toml_key(key: str) -> str:
    if _BARE_KEY_RE.fullmatch(key):
        return key
    return _toml_string(key)


def _toml_string(value: str) -> str:
    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'
